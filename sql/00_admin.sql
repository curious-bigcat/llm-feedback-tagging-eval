-- 00_admin.sql: run as ACCOUNTADMIN. Creates the workspace and the evaluation role with the privileges
-- listed in the recommendations doc (Step 2). Everything else runs as VOC_EVAL_ROLE.

USE ROLE ACCOUNTADMIN;

CREATE DATABASE IF NOT EXISTS VOC_EVAL COMMENT = 'Feedback-tagging evaluation methodology on NHS FFT open data';
CREATE SCHEMA IF NOT EXISTS VOC_EVAL.HARNESS;

CREATE ROLE IF NOT EXISTS VOC_EVAL_ROLE COMMENT = 'Runs the VOC evaluation harness';
GRANT ROLE VOC_EVAL_ROLE TO USER IDENTIFIER($EVAL_USER);  -- SET EVAL_USER = '<your user>'; first
GRANT ROLE VOC_EVAL_ROLE TO ROLE SYSADMIN;

-- Doc Step 2 privileges.
GRANT DATABASE ROLE SNOWFLAKE.CORTEX_USER TO ROLE VOC_EVAL_ROLE;
GRANT USE AI FUNCTIONS ON ACCOUNT TO ROLE VOC_EVAL_ROLE;
GRANT EXECUTE TASK ON ACCOUNT TO ROLE VOC_EVAL_ROLE;

-- Workspace: the role owns the schema, so it can create tables, views, stages, procedures, tasks,
-- notebooks and the Streamlit review app in it.
GRANT USAGE ON DATABASE VOC_EVAL TO ROLE VOC_EVAL_ROLE;
GRANT OWNERSHIP ON SCHEMA VOC_EVAL.HARNESS TO ROLE VOC_EVAL_ROLE COPY CURRENT GRANTS;
GRANT CREATE EXTERNAL AGENT ON SCHEMA VOC_EVAL.HARNESS TO ROLE VOC_EVAL_ROLE;
GRANT CREATE TASK ON SCHEMA VOC_EVAL.HARNESS TO ROLE VOC_EVAL_ROLE;
GRANT USAGE ON WAREHOUSE DEMO_WH TO ROLE VOC_EVAL_ROLE;
